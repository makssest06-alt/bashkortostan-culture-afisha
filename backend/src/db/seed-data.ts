export type MockWeekday = 'mon' | 'tue' | 'wed' | 'thu' | 'fri' | 'sat' | 'sun';

export type SeedSchedule =
  | {
      kind: 'offset';
      day_offset: number;
      time: string;
      duration_min?: number;
      status?: OccurrenceStatus;
      status_is_verified?: boolean;
      availability?: Availability;
      previous?: { day_offset: number; time: string };
    }
  | {
      kind: 'weekday';
      weekday: MockWeekday;
      week?: 0 | 1 | 2;
      time: string;
      duration_min?: number;
      status?: OccurrenceStatus;
      status_is_verified?: boolean;
      availability?: Availability;
    }
  | {
      kind: 'period';
      from_offset: number;
      to_offset: number;
      status?: OccurrenceStatus;
      status_is_verified?: boolean;
      availability?: Availability;
    };

export interface SeedOffer {
  name?: string;
  rub: number | null;
  audience?: OfferAudience;
  is_free?: boolean;
}


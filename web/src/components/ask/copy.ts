export type AskCopyKey = keyof typeof ASK_COPY;

/** Подпись страницы на языке интерфейса с подстановкой {имя}. */
export function askText(key: AskCopyKey, lang: Lang, vars?: Record<string, string | number>): string {
  const entry: LocalizedText = ASK_COPY[key];
  const template = entry[lang] || entry.ru;
  if (!vars) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : placeholder,
  );
}

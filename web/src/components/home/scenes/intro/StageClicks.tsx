/**
 * Клики сквозь пустые блоки секции.
 *
 * При склейке сцен секция следующей сцены поднята на высоту экрана и лежит поверх нижней части экрана
 * текущей. Экран следующей сцены спрятан, но сама секция и блок-распорка закрепления остаются на месте
 * и перехватывают клики: ссылка или поле внизу экрана не нажимаются. Поэтому у своих секций клики
 * выключены, а у их экранов включены обратно.
 *
 * Правило касается только секции с этим id. От чужой секции, которая лежит поверх нашего экрана,
 * оно не спасает: для этого экран сцены ai дополнительно поднят по z-index (см. ai/index.tsx).
 */
export function StageClicks({ id }: { id: string }) {
  const section = `.scene[data-scene="${id}"]`;
  return (
    <style href={`scene-clicks-${id}`} precedence="default">
      {`${section}{pointer-events:none}${section} .scene-stage{pointer-events:auto}`}
    </style>
  );
}

import { lerp, mixPose, POSE, smooth, span } from '../../scene-kit/math';
import type { SceneDef, SceneEnv, TokenPose } from '../../scene-kit/types';
import { chooseEntryPose } from '../choose/pose';

/**
 * Поза в начале сцены: жетон в центре стоит ребром (S11 заканчивается поворотом на 90 градусов
 * вокруг вертикальной оси после полуоборота вокруг горизонтальной: кадры 409-413).
 */
function startPose(env: SceneEnv): TokenPose {
  return { ...POSE, scale: env.mobile ? 0.56 : 0.24, rx: Math.PI, ry: Math.PI / 2 };
}

/**
 * popular (S12): волосяные линии, раскрытие панелей, горизонтальная лента с популярными событиями.
 *
 * Длина закрепления. В референсе 51 кадр (около 6,6 экрана) на ленту из четырёх широких панелей.
 * У нас пять событий: лента длиннее на одну пару панелей, поэтому и закрепление длиннее в той же
 * пропорции (64 кадра, 8,3 экрана). Скорость ленты та же: около 1,2px по горизонтали на 1px прокрутки.
 *
 * Жетон: первые 9 % сцены (кадры 413-418,5) разворачивается из положения ребром лицом к зрителю,
 * затем его закрывают панели (они выше холста). Пока он закрыт, поза переезжает к позе входа сцены choose,
 * и к концу закрепления жетон уже ждёт под последней панелью: полоса уезжает вверх, он снова виден.
 *
 * Стыки. Начало: x 0, y 0, scale 0.24 (телефон 0.56), rx PI, ry PI / 2, rz 0, opacity 1: этим кончается cities.
 * Конец: поза входа choose (../choose/pose.ts, choosePoseAt(0)): x 0, y 0.01, scale 0.234, rx 0, ry PI, rz 0.
 */
export const def: SceneDef = {
  id: 'popular',
  pinVh: 5.6,
  pinVhMobile: 4.6,
  // Полоса уезжает вверх обычной прокруткой (кадры 464-468), снизу поднимается знак следующей сцены.
  exit: 'scroll',
  // Фон рисует подложка сцены (свечение сверху по центру, как в референсе), боковое свечение выключено.
  glow: 0,
  token: (p, env) => {
    const start = startPose(env);
    // Разворот к зрителю. Вместе с ним жетон доворачивается в своей плоскости (rz): после полуоборота
    // вокруг горизонтальной оси в cities лицо иначе встало бы вверх ногами.
    const turn = env.reduced ? 0 : smooth(span(p, 0.008, 0.09));
    const turned: TokenPose = { ...start, ry: lerp(Math.PI / 2, Math.PI, turn), rz: Math.PI * turn };
    // Под панелями жетон не виден: меняем позу на позу входа следующей сцены без видимого движения.
    const pose = mixPose(turned, chooseEntryPose(env), smooth(span(p, 0.3, 0.5)));
    // На телефоне первая панель закрывает центр сразу, на компьютере к кадру 420-421 (12 % сцены).
    const hidden = env.mobile || env.reduced ? span(p, 0.01, 0.05) : span(p, 0.12, 0.15);
    const back = span(p, 0.965, 0.99);
    return { ...pose, opacity: Math.max(1 - hidden, back) };
  },
};

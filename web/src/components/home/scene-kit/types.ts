/**
 * Контракт сцен главной. Только типы: файл безопасно импортировать откуда угодно,
 * в том числе из def.ts сцен (def.ts не должен импортировать ничего другого из scene-kit,
 * кроме ./types и ./math, иначе получится цикл с registry.ts).
 */

/**
 * Поза жетона.
 * x, y: смещение центра от центра окна в долях ширины и высоты окна
 *       (0, 0 = центр; x = 0.5 правый край; y = 0.5 нижний край).
 * scale: диаметр жетона в долях ШИРИНЫ окна (как в спецификациях: 0.309 = 30,9 % W).
 * rx, ry, rz: повороты в радианах (порядок Эйлера XYZ). При нулях жетон лежит лицом к зрителю.
 * opacity: 0..1.
 * mode: 'solid' медный жетон (по умолчанию), 'wire' чертёж.
 */
export type TokenPose = {
  x: number;
  y: number;
  scale: number;
  rx: number;
  ry: number;
  rz: number;
  opacity: number;
  mode?: 'solid' | 'wire';
};

/** Окружение сцены: размер окна, телефон ли это (ширина < 768) и просит ли человек меньше движения. */
export type SceneEnv = {
  w: number;
  h: number;
  mobile: boolean;
  reduced: boolean;
};

/** Цвет шапки: 'light' светлая шапка на тёмной сцене (по умолчанию), 'dark' тёмная на светлой. */
export type HeaderTone = 'light' | 'dark';

export type SceneDef = {
  /** Идентификатор сцены: совпадает с именем каталога в scenes/. */
  id: string;
  /** Длина закрепления на компьютере, в экранах. 0 означает обычный поток. */
  pinVh: number;
  /** Длина закрепления на телефоне (ширина < 768). Не задано: как pinVh. 0: на телефоне обычный поток. */
  pinVhMobile?: number;
  /** Сцена всегда идёт обычным потоком, без закрепления. */
  flow?: boolean;
  /** Поза жетона по локальному прогрессу 0..1. Нет функции или вернула null: жетон плавно гаснет. */
  token?: (p: number, env: SceneEnv) => TokenPose | null;
  /** Цвет шапки, пока сцена под ней. По умолчанию 'light'. */
  headerTone?: HeaderTone;

  // --- Необязательные дополнения каркаса -------------------------------------------------------

  /** Яркость фонового свечения 0..1: число или функция прогресса. По умолчанию 1. */
  glow?: number | ((p: number, env: SceneEnv) => number);
  /**
   * Как сцена входит после закреплённой сцены. 'cut' (по умолчанию): склейка на месте, без перелистывания.
   * 'scroll': прошлая сцена уезжает вверх обычной прокруткой, эта въезжает снизу.
   */
  enter?: 'cut' | 'scroll';
  /** Как сцена выходит перед следующей закреплённой сценой. Значения те же, что у enter. */
  exit?: 'cut' | 'scroll';
};

/** Идентификаторы сцен главной по порядку. */
export const SCENE_IDS = [
  'intro',
  'hero',
  'ai',
  'gallery',
  'fullscreen',
  'thermal',
  'blueprint',
  'wordmark',
  'filters',
  'dedup',
  'trust',
  'cities',
  'popular',
  'choose',
  'footer',
] as const;

export type SceneId = (typeof SCENE_IDS)[number];

/** Раскладка сцены при текущем окружении: считается в registry.ts из def и соседей. */
export type SceneLayout = {
  index: number;
  /** Сцена закреплена (иначе обычный поток). */
  pinned: boolean;
  /** Длина закрепления в экранах при текущем окружении. */
  pinVh: number;
  /** Склейка с прошлой сценой: секция наложена на её хвост, экран спрятан до начала. */
  cutIn: boolean;
  /** Склейка со следующей сценой: экран прячется после конца закрепления. */
  cutOut: boolean;
};
